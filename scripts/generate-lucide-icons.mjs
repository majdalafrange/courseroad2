// One-off/rerunnable generator: pulls the handful of Lucide icons this app
// actually uses out of @iconify-json/lucide's full collection and writes
// them as a small static module, so the shipped bundle carries only the
// ~30 icons GIcon.vue references instead of the whole ~1600-icon set.
//
// Run with: node scripts/generate-lucide-icons.mjs
// Add a new icon by adding its Lucide name to ICON_MAP in GIcon.vue and to
// the `names` list below, then rerun.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const collectionPath = fileURLToPath(
  import.meta.resolve("@iconify-json/lucide/icons.json"),
);
const collection = JSON.parse(readFileSync(collectionPath, "utf8"));

const names = [
  "plus",
  "x",
  "more-vertical",
  "pencil",
  "trash-2",
  "copy",
  "sun",
  "moon",
  "info",
  "alert-circle",
  "download",
  "upload",
  "search",
  "undo-2",
  "redo-2",
  "log-in",
  "log-out",
  "check",
  "cloud",
  "triangle-alert",
  "chevron-down",
  "chevron-right",
  "map",
  "share-2",
  "message-square",
  "settings",
  "monitor",
  "panel-left",
  "panel-right",
  "external-link",
  "star",
  "arrow-left",
  "arrow-left-right",
  "cloud-download",
  "cloud-sync",
  "loader",
  "cloud-alert",
  "save-off",
  "save",
  "cloud-check",
];

function resolve(name) {
  const direct = collection.icons[name];
  if (direct) return direct;
  const alias = collection.aliases?.[name];
  if (alias) return resolve(alias.parent);
  throw new Error(`Icon "${name}" not found in @iconify-json/lucide`);
}

const entries = names.map((name) => {
  const { body } = resolve(name);
  return `  "${name}": { body: ${JSON.stringify(body)}, width: ${collection.width}, height: ${collection.height} },`;
});

const out = `// Generated by scripts/generate-lucide-icons.mjs. Do not edit by hand;
// rerun the script to add or update icons.
import type { IconifyIcon } from "@iconify/vue/offline";

export const LUCIDE_ICONS: Record<string, IconifyIcon> = {
${entries.join("\n")}
};
`;

writeFileSync(
  fileURLToPath(new URL("../src/design/lucideIcons.ts", import.meta.url)),
  out,
);
console.log(`Wrote ${names.length} icons to src/design/lucideIcons.ts`);
